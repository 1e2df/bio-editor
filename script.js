const LINK_NAMES = { discord: 'Discord', x: 'X', instagram: 'Instagram', tiktok: 'TikTok', youtube: 'YouTube', github: 'GitHub', twitch: 'Twitch', spotify: 'Spotify', link: 'Link' };

function isVideoFile(src) {
  return /\.(mp4|webm|mov)(\?|#|$)/i.test(src);
}

function applySiteConfig(cfg) {
  if (cfg.name) document.title = cfg.name;

  const avatar = document.querySelector('.profile-picture');
  if (avatar && cfg.avatar) avatar.src = cfg.avatar;

  const music = document.getElementById('background-music');
  if (music && cfg.music) music.src = cfg.music;

  // Background: <video> for video files, <img> for images.
  const current = document.getElementById('background');
  if (current && cfg.background) {
    const video = cfg.backgroundType ? cfg.backgroundType === 'video' : isVideoFile(cfg.background);
    const el = document.createElement(video ? 'video' : 'img');
    el.id = 'background';
    el.style.cssText = current.style.cssText;
    if (video) {
      el.autoplay = true; el.loop = true; el.muted = true; el.playsInline = true;
    }
    el.src = cfg.background;
    current.replaceWith(el);
  }

  // Links: a URL opens in a new tab; anything else (e.g. a Discord username) is copied.
  const container = document.querySelector('.social-links');
  if (container) {
    container.innerHTML = '';
    (cfg.links || []).forEach(link => {
      if (!link || !link.value) return;
      const type = LINK_ICONS[link.type] ? link.type : 'link';
      const isUrl = /^https?:\/\//i.test(link.value);
      const a = document.createElement('a');
      a.href = isUrl ? link.value : '#';
      if (isUrl) { a.target = '_blank'; a.rel = 'noopener'; }
      a.title = `${LINK_NAMES[type]}: ${link.value}` + (isUrl ? '' : ' (clique para copiar)');
      a.innerHTML = `<svg class="social-icon" viewBox="0 0 24 24" style="color:#fff" aria-label="${LINK_NAMES[type]}">${LINK_ICONS[type]}</svg>`;
      if (!isUrl) {
        a.addEventListener('click', e => {
          e.preventDefault();
          navigator.clipboard.writeText(link.value).then(() => { a.title = `Copiado: ${link.value}`; }).catch(() => {});
        });
      }
      container.appendChild(a);
    });
  }
}

